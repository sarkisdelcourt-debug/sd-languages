import type { CefrLevel } from "../../types.js";
import type { ExerciseTopic, VocabSet } from "../types.js";

/**
 * Listes de verbes (22/10/2026). ATTENTION : `en` porte ici l'infinitif ALLEMAND,
 * `fr` l'infinitif français. Chaque verbe est écrit « allemand = français ».
 */
function set(
  id: string,
  topic: ExerciseTopic,
  level: CefrLevel,
  title: string,
  skill: string,
  words: string[],
): VocabSet {
  return {
    id,
    topic,
    level,
    title,
    skill,
    items: words.map((w) => {
      const [en, fr] = w.split(" = ");
      return { en: en!, fr: fr! };
    }),
  };
}

