import type { ExerciseTopic, VocabSet } from "../types.js";

/**
 * Listes de vocabulaire complémentaires (10/11/2026). ATTENTION : `en` porte ici le texte ALLEMAND,
 * `fr` la traduction française. Chaque mot est écrit « allemand = français » puis éclaté par `set`.
 */
function set(
  id: string,
  topic: ExerciseTopic,
  level: CefrLevel,
  title: string,
  skill: string,
  words: string[],
): VocabSet {
  return {
    id,
    topic,
    level,
    title,
    skill,
    items: words.map((w) => {
      const [en, fr] = w.split(" = ");
      return { en: en!, fr: fr! };
    }),
  };
}

